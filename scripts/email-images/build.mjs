#!/usr/bin/env node
/**
 * Builds the email images (privacy page v1, phase 2):
 *
 *   node scripts/email-images/build.mjs
 *
 * Writes public/images/email/<name>.png for every entry in lib.mjs's SPECS — the pending pass, the
 * fifty numbered passes, the waiting pass, the three headings and the signature — as PNG-8, each at
 * most 60 KB, and functions/src/emailImageManifest.ts (each image's size, version and alt text), which
 * the email templates read.
 *
 * ⚠️ TWO IMAGES ARE NICK'S, NOT THE TEMPLATE'S: pass-pending and heading-confirm were supplied (the
 * pack, 2 Nov) and their originals live in ./supplied/. Their pixels are taken from those files and only
 * quantised. The templates reproduce them closely (EM-8 records how closely) but not within 1%: the
 * supplied art was rasterised by a different renderer, and every glyph edge differs slightly.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { launch, render, decodeInPage, encodePng8, SPECS, OUT_DIR, MAX_BYTES, ROOT } from "./lib.mjs";

const SUPPLIED = join(ROOT, "scripts/email-images/supplied");
export const sourcePixels = async (browser, page, spec) => {
  const sup = join(SUPPLIED, `${spec.name}.png`);
  if (existsSync(sup)) return { ...(await decodeInPage(page, readFileSync(sup))), supplied: true };
  const r = await render(browser, spec);
  const want = spec.file === "pass.html" ? ["Special Elite", "Source Serif 4", ...(spec.vars.OF ? ["Source Sans 3"] : [])] : ["Special Elite"];
  for (const f of want) if (!r.fonts.includes(f)) throw new Error(`${spec.name}: ${f} did not load, so the render is not the brand (got ${r.fonts.join(", ")})`);
  return { ...r, supplied: false };
};

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  const browser = await launch();
  const page = await browser.newPage();
  const manifest = {};
  for (const spec of SPECS) {
    const px = await sourcePixels(browser, page, spec);
    const png = encodePng8(px.w, px.h, px.rgba);
    if (png.length > MAX_BYTES) throw new Error(`${spec.name}: ${png.length} bytes, over the 60 KB limit`);
    writeFileSync(join(OUT_DIR, `${spec.name}.png`), png);
    manifest[spec.name] = {
      path: `/images/email/${spec.name}.png`,
      version: createHash("md5").update(png).digest("hex").slice(0, 8),
      /* The image is drawn at 2×; the email shows it at half its pixel size. */
      width: px.w / 2, height: px.h / 2, alt: spec.alt,
    };
    console.log(`${spec.name.padEnd(16)} ${px.w}×${px.h}  ${(png.length / 1024).toFixed(1)} KB${px.supplied ? "  (supplied)" : ""}`);
  }
  await browser.close();
  const ts = `/**
 * GENERATED by scripts/email-images/build.mjs — do not edit by hand (run the script).
 *
 * The email images (privacy page v1, phase 2): each one's path, version (the first eight hex digits of
 * the file's md5), its size as the email shows it (half the 2× file's pixels), and its alt text, so an
 * email with images off still reads in order.
 */
export interface EmailImage { path: string; version: string; width: number; height: number; alt: string }
export const EMAIL_IMAGES: Record<string, EmailImage> = ${JSON.stringify(manifest, null, 2)};
`;
  writeFileSync(join(ROOT, "functions/src/emailImageManifest.ts"), ts);
  console.log(`wrote ${Object.keys(manifest).length} images and functions/src/emailImageManifest.ts`);
}
